export function findTemplates(
  items: Template[],
  query: string,
  category: string,
  department = "",
  style = "",
  tone = "",
) {
  const terms = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  return items.filter(
    (t) =>
      t.published &&
      terms.every((q) =>
        [
          t.name,
          t.cover,
          t.subtitle,
          t.description,
          t.category,
          t.department,
          ...t.tags,
        ]
          .join(" ")
          .toLowerCase()
          .includes(q),
      ) &&
      (!category ||
        category === "All templates" ||
        (category === "College"
          ? t.handoffId
            ? t.category === "College"
            : t.family < 12
          : t.category === category)) &&
      (!department || t.department === department) &&
      (!style || t.style === style) &&
      (!tone || (tone === "Dark" ? isDark(t.bg) : !isDark(t.bg))),
  );
}
function isDark(hex: string) {
  return (
    [1, 3, 5].reduce(
      (sum, offset, i) =>
        sum +
        parseInt(hex.slice(offset, offset + 2), 16) *
          [0.2126, 0.7152, 0.0722][i],
      0,
    ) < 130
  );
}
